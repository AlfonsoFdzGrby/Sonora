export function icon(name, size = 18) {
  return `<svg class="icon" viewBox="0 0 24 24" width="${size}" height="${size}" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${PATHS[name] ?? ''}</svg>`;
}

export function mountIcons(root = document) {
  root.querySelectorAll('[data-icon]').forEach((el) => {
    el.innerHTML = icon(el.dataset.icon, Number(el.dataset.size) || 18);
  });
}

export function coverHtml(url, seed, extraClass = '', iconSize = 28) {
  if (url) {
    return `<img class="cover ${extraClass}" src="${esc(url)}" alt="" loading="lazy" decoding="async" draggable="false" data-seed="${esc(seed)}">`;
  }
  const hue = hueFrom(seed);
  return `<div class="cover ph ${extraClass}" style="--h:${hue};--h2:${(hue + 45) % 360}">${icon('music', iconSize)}</div>`;
}

export function bindCoverFallback(root) {
  root.querySelectorAll('img.cover').forEach((img) => {
    img.addEventListener(
      'error',
      () => {
        const hue = hueFrom(img.dataset.seed || '');
        const placeholder = document.createElement('div');
        placeholder.className = img.className.replace('cover', 'cover ph');
        placeholder.style.setProperty('--h', hue);
        placeholder.style.setProperty('--h2', (hue + 45) % 360);
        placeholder.innerHTML = icon('music', 28);
        img.replaceWith(placeholder);
      },
      { once: true },
    );
  });
}
